"""``odoo-typing-root``: generate a ``mypy_path`` root where every addon is ``odoo.addons.<name>``.

Odoo 18 makes an addon importable only as ``odoo.addons.<name>`` (``initialize_sys_path``
extends ``odoo.addons.__path__`` with the addons paths), so addons import each other,
and their own ``tests.common``, that way. mypy cannot merge directories into the
regular package ``odoo/addons``, so the overlay is a copy of the ``odoo`` package made
of symlinks::

    <overlay_root>/odoo/<entry>            -> <odoo_path>/<entry>   (all but addons/)
    <overlay_root>/odoo/addons/__init__.py -> <odoo_path>/addons/__init__.py  (Odoo < 19)
    <overlay_root>/odoo/addons/<name>      -> the addon's directory (core and addons_path)

Odoo 19+ has no ``odoo/addons/__init__.py`` (a namespace package); its overlay has none.

Usage: ``odoo-typing-root [--config pyproject.toml] [--output DIR]``. The settings
come from the ``[tool.odoo_typing]`` table (``odoo_path``, ``addons_path``, and
``overlay_root`` as the default output). Run it again after adding or removing addons.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from collections.abc import Sequence
from pathlib import Path

from odoo_typing.addons import AddonIndex
from odoo_typing.config import OVERLAY_MARKER as MARKER
from odoo_typing.config import ConfigError, Settings, load_settings

__all__ = ["MARKER", "OverlayError", "build_overlay", "main"]

SKIPPED = frozenset({"addons", "__pycache__"})


class OverlayError(Exception):
    """Raised when the overlay root cannot be generated."""


def build_overlay(settings: Settings, output: Path) -> int:
    """Generate (or regenerate) the overlay root.

    Args:
        settings: Plugin settings; ``odoo_path`` must be the real ``odoo`` package.
        output: The overlay root, the directory to put on ``mypy_path``.

    Returns:
        The number of addons linked.

    Raises:
        OverlayError: If ``output`` holds an ``odoo`` directory that this command did
            not generate, or the Odoo package itself.
    """
    odoo = settings.odoo_path.resolve()
    output = output.absolute()
    if odoo.is_relative_to(output.resolve()):
        raise OverlayError(f"odoo_path {odoo} is inside the overlay root {output}")
    package = output / "odoo"
    _remove_previous(output, package)
    package.mkdir(parents=True)
    for entry in sorted(odoo.iterdir()):
        if entry.name not in SKIPPED:
            (package / entry.name).symlink_to(entry)
    addons_dir = package / "addons"
    addons_dir.mkdir()
    if (odoo / "addons" / "__init__.py").is_file():
        (addons_dir / "__init__.py").symlink_to(odoo / "addons" / "__init__.py")
    index = AddonIndex(odoo, settings.addons_paths)
    for addon in index.addons.values():
        (addons_dir / addon.name).symlink_to(addon.path, target_is_directory=True)
    (output / MARKER).write_text(f"generated by odoo-typing-root from {odoo}\n")
    return len(index.addons)


def _remove_previous(output: Path, package: Path) -> None:
    """Remove an earlier overlay (or the plain ``odoo`` symlink of the simple setup)."""
    if package.is_symlink():
        package.unlink()
    elif package.exists():
        if not (output / MARKER).is_file():
            raise OverlayError(
                f"{package} was not generated by odoo-typing-root; "
                "remove it or choose another output directory"
            )
        # Only symlinks and the directories created here: rmtree unlinks symlinks
        # without following them, so the linked Odoo and addons are left untouched.
        shutil.rmtree(package)


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point of ``odoo-typing-root``.

    Args:
        argv: Arguments, without the program name (default: ``sys.argv[1:]``).

    Returns:
        Exit status: 0 on success, 2 on a configuration or generation error.
    """
    parser = argparse.ArgumentParser(
        prog="odoo-typing-root",
        description="Generate a mypy_path root in which every addon is odoo.addons.<name>.",
    )
    parser.add_argument("--config", default="pyproject.toml", help="default: %(default)s")
    parser.add_argument("--output", help="overlay root (default: overlay_root in the config)")
    args = parser.parse_args(argv)
    try:
        settings = load_settings(args.config, require_overlay=False)
        output = Path(args.output) if args.output else settings.overlay_root
        if output is None:
            raise ConfigError("no output: set overlay_root in [tool.odoo_typing] or pass --output")
        count = build_overlay(settings, output)
    except (ConfigError, OverlayError, OSError) as exc:
        print(f"odoo-typing-root: error: {exc}", file=sys.stderr)
        return 2
    print(f"odoo-typing-root: wrote {output} ({count} addons)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
