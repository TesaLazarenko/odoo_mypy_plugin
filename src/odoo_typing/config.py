"""Plugin settings, read from the config file mypy uses.

In ``pyproject.toml`` (or another TOML config), the ``[tool.odoo_typing]`` table::

    [tool.odoo_typing]
    odoo_path = "/usr/lib/python3/dist-packages/odoo"   # dir that holds release.py
    addons_path = ["addons", "../enterprise"]           # relative to pyproject.toml
    overlay_root = ".odoo-root"   # optional: generated by odoo-typing-root
    scan_cache_dir = ""           # optional: keep addon scans only in mypy's cache

In ``mypy.ini``, ``.mypy.ini`` or ``setup.cfg``, the ``[odoo_typing]`` section, with
``addons_path`` entries separated by commas or newlines::

    [odoo_typing]
    odoo_path = /usr/lib/python3/dist-packages/odoo
    addons_path = addons, ../enterprise

An INI config without that section falls back to the ``[tool.odoo_typing]`` table of a
``pyproject.toml`` next to it. Relative paths are relative to the file they are in.
Without ``odoo_path``, the ``odoo`` package is looked for on ``mypy_path``, then in
mypy's own interpreter.

This is a boundary module: raw TOML/INI values are validated and turned into
:class:`Settings`.
"""

from __future__ import annotations

import configparser
import importlib.util
import os
import re
import sys
import tomllib
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from odoo_typing.addons import CORE_PREFIX, MANIFEST_NAMES, find_manifest, may_be_addon
from odoo_typing.compat import SUPPORTED_VERSIONS

__all__ = ["OVERLAY_MARKER", "ConfigError", "Settings", "default_scan_cache_dir", "load_settings"]

SECTION = "odoo_typing"
WHERE = f"[tool.{SECTION}] (pyproject.toml) or [{SECTION}] (mypy.ini, setup.cfg)"
LIST_SEPARATOR = re.compile(r"[,\n]")
# What ``env[name]`` is when ``name`` is not a literal: ``Any``, or Odoo's ``BaseModel``.
DYNAMIC_ENV_CHOICES = ("any", "base")
# File that marks an overlay root generated by ``odoo-typing-root`` (odoo_typing.overlay).
OVERLAY_MARKER = ".odoo-typing-root"
OPTIONS = (
    "odoo_path",
    "odoo_version",
    "addons_path",
    "overlay_root",
    "dynamic_env",
    "vals_ignore_keys",
    "literal_selection",
    "required_values",
    "rebound_variables",
    "scan_cache_dir",
)
# Options that are lists; in an INI file, entries separated by commas or newlines.
LIST_OPTIONS = ("addons_path", "vals_ignore_keys")
# Spellings of a flag in an INI file (TOML has booleans).
FLAG_VALUES = {"true": True, "yes": True, "on": True, "1": True}
FLAG_VALUES |= {"false": False, "no": False, "off": False, "0": False}
# Keys of ``vals`` not checked against the model's fields: fields created in the
# database (manual ``x_`` fields, Studio's ``x_studio_``).
DEFAULT_VALS_IGNORE_KEYS = ("x_*",)


class ConfigError(Exception):
    """Raised when the plugin configuration is missing or invalid."""


@dataclass(frozen=True, slots=True)
class Settings:
    """Validated plugin settings.

    Attributes:
        odoo_path: Directory of the ``odoo`` package (contains ``release.py``).
        addons_paths: Extra addons directories, besides ``<odoo_path>/addons``.
        overlay_root: The ``mypy_path`` root generated by ``odoo-typing-root``, in
            which every addon is the package ``odoo.addons.<name>``; ``None`` if the
            ``addons_path`` addons are top-level packages on ``mypy_path``.
        dynamic_env: Type of ``env[name]`` when ``name`` is not a literal: ``"any"``
            (default) or ``"base"`` (``BaseModel``, so reading a field is an error).
        odoo_version: The Odoo major version the checks target (``odoo_version``);
            the plugin requires it, ``odoo-typing-root`` does not need it.
        vals_ignore_keys: Glob patterns of ``vals`` keys that are not reported as
            unknown fields (``fnmatch``, case-sensitive).
        literal_selection: Read a ``Selection`` field with literal keys as
            ``Literal[<keys>] | Literal[False]`` instead of ``str | Literal[False]``.
        required_values: Read a required field (``required=True``, as the merged
            definitions of the model leave it) and ``display_name`` without
            ``| Literal[False]`` (the default; ``False``: as Odoo declares them).
        rebound_variables: Give a local variable that its function binds more than
            once the type of each value at its binding (the default; ``False``: the
            type of its first value, as mypy infers it), see :mod:`odoo_typing.rebound`.
        scan_cache_dir: Where addon scans are kept for every project and mypy cache
            (:class:`odoo_typing.scan_store.ScanStore`); ``None``: only in mypy's cache.
    """

    odoo_path: Path
    addons_paths: tuple[Path, ...]
    overlay_root: Path | None = None
    dynamic_env: str = "any"
    odoo_version: int | None = None
    vals_ignore_keys: tuple[str, ...] = DEFAULT_VALS_IGNORE_KEYS
    literal_selection: bool = False
    required_values: bool = True
    rebound_variables: bool = True
    scan_cache_dir: Path | None = None

    def option_data(self) -> list[str]:
        """The options that change check results; part of every module's cache key."""
        return [
            f"dynamic_env={self.dynamic_env}",
            f"odoo_version={self.odoo_version}",
            f"vals_ignore_keys={','.join(self.vals_ignore_keys)}",
            f"literal_selection={self.literal_selection}",
            f"required_values={self.required_values}",
            f"rebound_variables={self.rebound_variables}",
        ]

    @property
    def custom_prefix(self) -> str:
        """Module name template of the ``addons_paths`` addons (see ``AddonIndex``)."""
        return CORE_PREFIX if self.overlay_root is not None else "{}"


def load_settings(
    config_file: str | None, mypy_path: Sequence[str] = (), *, require_overlay: bool = True
) -> Settings:
    """Load settings from mypy's config file, falling back to auto-detection.

    Args:
        config_file: Path of the config file mypy was started with, if any.
        mypy_path: mypy's ``mypy_path``, searched for the ``odoo`` package if
            ``odoo_path`` is not set.
        require_overlay: Check that a configured ``overlay_root`` was generated
            (``odoo-typing-root``, which generates it, does not).

    Returns:
        Validated settings.

    Raises:
        ConfigError: If the config cannot be read, the values have the wrong shape
            or Odoo cannot be found.
    """
    table, base_dir = _read_table(config_file)
    _check_option_names(table)
    return Settings(
        odoo_path=_odoo_path(table.get("odoo_path"), base_dir, mypy_path),
        addons_paths=_addons_paths(table.get("addons_path", []), base_dir),
        overlay_root=_overlay_root(table.get("overlay_root"), base_dir, require_overlay),
        dynamic_env=_choice("dynamic_env", table.get("dynamic_env", "any"), DYNAMIC_ENV_CHOICES),
        odoo_version=_odoo_version(table.get("odoo_version")),
        vals_ignore_keys=_patterns(
            "vals_ignore_keys", table.get("vals_ignore_keys", list(DEFAULT_VALS_IGNORE_KEYS))
        ),
        literal_selection=_flag("literal_selection", table.get("literal_selection", False)),
        required_values=_flag("required_values", table.get("required_values", True)),
        rebound_variables=_flag("rebound_variables", table.get("rebound_variables", True)),
        scan_cache_dir=_scan_cache_dir(table, base_dir),
    )


def _flag(name: str, value: object) -> bool:
    if isinstance(value, bool):
        return value
    if isinstance(value, str) and value.strip().lower() in FLAG_VALUES:
        return FLAG_VALUES[value.strip().lower()]
    raise ConfigError(f"{name} must be true or false, got {value!r}")


def _patterns(name: str, value: object) -> tuple[str, ...]:
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise ConfigError(f"{name} must be a list of strings")
    return tuple(value)


def _odoo_version(value: object) -> int | None:
    """``odoo_version = 18`` (an INI file gives the string ``"18"``)."""
    if value is None:
        return None
    if isinstance(value, str) and value.isdigit():
        value = int(value)
    if isinstance(value, bool) or not isinstance(value, int) or value not in SUPPORTED_VERSIONS:
        allowed = ", ".join(str(version) for version in SUPPORTED_VERSIONS)
        raise ConfigError(f"odoo_version must be one of {allowed}, not {value!r}")
    return value


def _check_option_names(table: dict[str, object]) -> None:
    for name in table:
        if name not in OPTIONS:
            known = ", ".join(OPTIONS)
            raise ConfigError(f'unknown option "{name}" in {WHERE}; known options: {known}')


def _choice(name: str, value: object, choices: tuple[str, ...]) -> str:
    if not isinstance(value, str) or value not in choices:
        allowed = ", ".join(f'"{choice}"' for choice in choices)
        raise ConfigError(f"{name} must be one of {allowed}, not {value!r}")
    return value


def _read_table(config_file: str | None) -> tuple[dict[str, object], Path]:
    """The plugin's settings in a config file, and the directory they are relative to."""
    if not config_file:
        return {}, Path.cwd()
    path = Path(config_file).resolve()
    if path.suffix == ".toml":
        return _toml_table(path), path.parent
    table = _ini_table(path)
    pyproject = path.parent / "pyproject.toml"
    if table is None and pyproject.is_file():
        return _toml_table(pyproject), path.parent
    return table or {}, path.parent


def _toml_table(path: Path) -> dict[str, object]:
    try:
        with path.open("rb") as handle:
            raw = tomllib.load(handle)
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        raise ConfigError(f"cannot read {path}: {exc}") from exc
    tool = raw.get("tool", {})
    section = tool.get(SECTION, {}) if isinstance(tool, dict) else {}
    if not isinstance(section, dict):
        raise ConfigError(f"[tool.{SECTION}] in {path} must be a table")
    return section


def _ini_table(path: Path) -> dict[str, object] | None:
    """The ``[odoo_typing]`` section of an INI file, list options as lists."""
    parser = configparser.ConfigParser(interpolation=None)
    try:
        with path.open(encoding="utf-8") as handle:
            parser.read_file(handle)
    except (OSError, UnicodeDecodeError, configparser.Error) as exc:
        raise ConfigError(f"cannot read {path}: {exc}") from exc
    if not parser.has_section(SECTION):
        return None
    table: dict[str, object] = dict(parser.items(SECTION))
    for name in LIST_OPTIONS:
        if name in table:
            entries = LIST_SEPARATOR.split(parser.get(SECTION, name))
            table[name] = [entry.strip() for entry in entries if entry.strip()]
    return table


def _odoo_path(value: object, base_dir: Path, mypy_path: Sequence[str]) -> Path:
    if value is None:
        path = _find_odoo(mypy_path)
    elif isinstance(value, str):
        path = _resolve(base_dir / value, "odoo_path")
    else:
        raise ConfigError("odoo_path must be a string")
    if not (path / "release.py").is_file():
        raise ConfigError(f"odoo_path {path} does not contain release.py")
    return path


def _resolve(path: Path, option: str) -> Path:
    """``path.resolve()``; a symlink loop is a configuration error.

    Up to Python 3.12 ``Path.resolve`` raises ``RuntimeError`` on a loop (3.13 returns the
    path, which then is no directory).
    """
    try:
        return path.resolve()
    except (OSError, RuntimeError) as exc:
        raise ConfigError(f"{option} {path} cannot be resolved: {exc}") from exc


def _scan_cache_dir(table: dict[str, object], base_dir: Path) -> Path | None:
    """The shared scan cache: the configured directory, ``None`` if it is ``""``."""
    if "scan_cache_dir" not in table:
        return default_scan_cache_dir()
    value = table["scan_cache_dir"]
    if not isinstance(value, str):
        raise ConfigError("scan_cache_dir must be a string")
    if not value.strip():
        return None
    try:
        expanded = Path(value).expanduser()
    except RuntimeError:  # "~" without a home (a container user with no passwd entry)
        print(
            f"odoo-typing: warning: scan_cache_dir {value} names a home directory that "
            "cannot be found; scans are kept in mypy's cache only",
            file=sys.stderr,
        )
        return None
    return base_dir / expanded


def default_scan_cache_dir() -> Path | None:
    """``$XDG_CACHE_HOME/odoo-typing/scans`` (``~/.cache`` by default); ``None`` without a home."""
    base = os.environ.get("XDG_CACHE_HOME", "")
    if not Path(base).is_absolute():  # the XDG spec ignores a relative value
        try:
            base = str(Path.home() / ".cache")
        except RuntimeError:
            return None
    return Path(base) / "odoo-typing" / "scans"


def _find_odoo(mypy_path: Sequence[str]) -> Path:
    """The ``odoo`` package on ``mypy_path``, else the one mypy's interpreter imports."""
    for entry in mypy_path:
        release = Path(entry) / "odoo" / "release.py"
        if release.is_file():
            # Through release.py: in an overlay root only the entries are symlinks.
            return release.resolve().parent
    spec = importlib.util.find_spec("odoo")
    if spec is None or not spec.submodule_search_locations:
        raise ConfigError(
            f"Odoo not found: set odoo_path in {WHERE}, or add the directory that "
            "contains the odoo package to mypy_path"
        )
    return Path(next(iter(spec.submodule_search_locations)))


def _overlay_root(value: object, base_dir: Path, required: bool) -> Path | None:
    if value is None:
        return None
    if not isinstance(value, str):
        raise ConfigError("overlay_root must be a string")
    path = _resolve(base_dir / value, "overlay_root")
    if required and not (path / OVERLAY_MARKER).is_file():
        raise ConfigError(
            f"overlay_root {path} is not generated (no {OVERLAY_MARKER} file); "
            "run odoo-typing-root to generate it"
        )
    return path


def _addons_paths(value: object, base_dir: Path) -> tuple[Path, ...]:
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise ConfigError("addons_path must be a list of strings")
    paths = tuple(_resolve(base_dir / item, "addons_path entry") for item in value)
    missing = [str(path) for path in paths if not path.is_dir()]
    if missing:
        raise ConfigError(f"addons_path entries are not directories: {', '.join(missing)}")
    for path in paths:
        _check_addons_dir(path)
    return paths


def _check_addons_dir(path: Path) -> None:
    """Reject an ``addons_path`` entry that holds no addon.

    Odoo 18 itself accepts such entries and then just finds no module there. For a
    type checker that is a silent failure: the files of the user's addons would
    belong to no addon, and their models would be reported as unknown. A subdirectory
    that cannot be read (``lost+found``) is just no addon (``find_manifest``).
    """
    try:
        if any(may_be_addon(child.name) and find_manifest(child) for child in path.iterdir()):
            return
    except OSError as exc:  # the entry itself cannot be listed
        raise ConfigError(f"cannot list addons_path entry {path}: {exc.strerror}") from exc
    if find_manifest(path):
        raise ConfigError(
            f"addons_path entry {path} is itself an addon; "
            f"list its parent directory {path.parent} instead"
        )
    raise ConfigError(
        f"addons_path entry {path} contains no addon "
        f"(no subdirectory with {' or '.join(MANIFEST_NAMES)}); "
        "list the directory that contains your addons"
    )
