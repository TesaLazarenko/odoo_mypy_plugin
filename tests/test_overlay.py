"""Unit tests for the ``odoo-typing-root`` overlay generator (no mypy run)."""

from __future__ import annotations

import os
from pathlib import Path

import pytest

from odoo_typing.config import Settings
from odoo_typing.overlay import OverlayError, build_overlay, main


def _addon(root: Path, name: str) -> Path:
    path = root / name
    path.mkdir(parents=True)
    (path / "__manifest__.py").write_text(repr({"name": name, "depends": []}))
    (path / "__init__.py").write_text("")
    return path


@pytest.fixture
def odoo(tmp_path: Path) -> Path:
    """A fake ``odoo`` package: a few entries, ``addons/`` with ``base``, a ``__pycache__``."""
    odoo = tmp_path / "dist" / "odoo"
    (odoo / "addons").mkdir(parents=True)
    (odoo / "__pycache__").mkdir()
    (odoo / "tools").mkdir()
    for name in ("__init__.py", "release.py", "models.py", "addons/__init__.py"):
        (odoo / name).write_text("")
    _addon(odoo / "addons", "base")
    return odoo


@pytest.fixture
def settings(tmp_path: Path, odoo: Path) -> Settings:
    _addon(tmp_path / "addons", "my_mod")
    _addon(tmp_path / "addons", "base")  # shadowed by the core addon, as in Odoo
    return Settings(odoo_path=odoo, addons_paths=(tmp_path / "addons",))


def _links(directory: Path) -> dict[str, Path]:
    return {
        entry.name: Path(os.readlink(entry)) for entry in directory.iterdir() if entry.is_symlink()
    }


def test_build_overlay_links_odoo_entries_except_addons_and_pycache(
    tmp_path: Path, odoo: Path, settings: Settings
) -> None:
    output = tmp_path / ".odoo-root"

    build_overlay(settings, output)

    links = _links(output / "odoo")
    assert links == {
        name: odoo / name for name in ("__init__.py", "models.py", "release.py", "tools")
    }
    assert (output / "odoo" / "addons").is_dir()
    assert not (output / "odoo" / "addons").is_symlink()


def test_build_overlay_links_core_and_custom_addons_core_wins_clash(
    tmp_path: Path, odoo: Path, settings: Settings
) -> None:
    output = tmp_path / ".odoo-root"

    count = build_overlay(settings, output)

    links = _links(output / "odoo" / "addons")
    assert links == {
        "__init__.py": odoo / "addons" / "__init__.py",
        "base": odoo / "addons" / "base",
        "my_mod": (tmp_path / "addons" / "my_mod").resolve(),
    }
    assert count == 2


def test_build_overlay_existing_overlay_is_rebuilt_and_targets_survive(
    tmp_path: Path, settings: Settings
) -> None:
    output = tmp_path / ".odoo-root"
    build_overlay(settings, output)
    gone = _addon(tmp_path / "addons", "gone")
    build_overlay(settings, output)
    (gone / "__manifest__.py").unlink()

    build_overlay(settings, output)

    assert "gone" not in _links(output / "odoo" / "addons")
    assert (gone / "__init__.py").is_file()
    assert (tmp_path / "addons" / "my_mod" / "__init__.py").is_file()


def test_build_overlay_namespace_odoo_addons_gets_no_init(
    tmp_path: Path, odoo: Path, settings: Settings
) -> None:
    # Odoo 19+: odoo.addons is a namespace package.
    (odoo / "addons" / "__init__.py").unlink()
    output = tmp_path / ".odoo-root"

    build_overlay(settings, output)

    assert not (output / "odoo" / "addons" / "__init__.py").exists()
    assert (output / "odoo" / "addons" / "my_mod").is_symlink()


def test_build_overlay_plain_odoo_symlink_is_replaced(
    tmp_path: Path, odoo: Path, settings: Settings
) -> None:
    output = tmp_path / ".odoo-root"
    output.mkdir()
    (output / "odoo").symlink_to(odoo)

    build_overlay(settings, output)

    assert not (output / "odoo").is_symlink()
    assert (odoo / "release.py").is_file()
    assert (output / "odoo" / "addons" / "my_mod").is_symlink()


def test_build_overlay_foreign_odoo_directory_raises(tmp_path: Path, settings: Settings) -> None:
    output = tmp_path / ".odoo-root"
    (output / "odoo").mkdir(parents=True)

    with pytest.raises(OverlayError, match="not generated by odoo-typing-root"):
        build_overlay(settings, output)


def test_build_overlay_odoo_path_inside_output_raises(tmp_path: Path, settings: Settings) -> None:
    output = tmp_path / "dist"

    with pytest.raises(OverlayError, match="odoo_path"):
        build_overlay(settings, output)


def _pyproject(tmp_path: Path, odoo: Path, overlay_root: str | None) -> Path:
    _addon(tmp_path / "addons", "my_mod")
    config = tmp_path / "pyproject.toml"
    text = f'[tool.odoo_typing]\nodoo_path = "{odoo}"\naddons_path = ["addons"]\n'
    if overlay_root is not None:
        text += f'overlay_root = "{overlay_root}"\n'
    config.write_text(text)
    return config


def test_main_config_with_overlay_root_writes_it_returns_0(
    tmp_path: Path, odoo: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    config = _pyproject(tmp_path, odoo, ".odoo-root")

    status = main(["--config", str(config)])

    assert status == 0
    assert (tmp_path / ".odoo-root" / "odoo" / "addons" / "my_mod").is_symlink()
    assert "2 addons" in capsys.readouterr().out


def test_main_output_option_overrides_config(tmp_path: Path, odoo: Path) -> None:
    config = _pyproject(tmp_path, odoo, None)

    status = main(["--config", str(config), "--output", str(tmp_path / "root")])

    assert status == 0
    assert (tmp_path / "root" / "odoo" / "release.py").is_symlink()


def test_main_without_output_returns_2_and_explains(
    tmp_path: Path, odoo: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    config = _pyproject(tmp_path, odoo, None)

    status = main(["--config", str(config)])

    assert status == 2
    assert "overlay_root" in capsys.readouterr().err


def test_main_config_error_returns_2(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    config = tmp_path / "pyproject.toml"
    config.write_text('[tool.odoo_typing]\nodoo_path = "nowhere"\n')

    status = main(["--config", str(config), "--output", str(tmp_path / "root")])

    assert status == 2
    assert "odoo-typing-root: error: " in capsys.readouterr().err
